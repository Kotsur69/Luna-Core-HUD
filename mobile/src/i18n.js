export const lang = (navigator.language || 'en').toLowerCase().startsWith('pl') ? 'pl' : 'en';
/** Intl locale for numbers, dates and times. */
export const locale = lang === 'pl' ? 'pl-PL' : 'en-GB';
export const t = (key) => STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
/** t() with {name} placeholders filled from `vars`. */
export const tf = (key, vars) => t(key).replace(/[{]([A-Za-z]+)[}]/g, (m, k) => (k in vars ? String(vars[k]) : m));
