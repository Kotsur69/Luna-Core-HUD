let currentLang = 'pl';

/** Substitutes {placeholders} with values from params. */
function interpolate(str, params) {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, key) => (key in params ? String(params[key]) : m));
}

/** Translates a key into the current language (fallback: PL -> the key itself). */
function t(key, params) {
  const dict = I18N_DICT[currentLang] || I18N_DICT.pl;
  const str = (key in dict ? dict[key] : I18N_DICT.pl[key]) ?? key;
  return interpolate(str, params);
}

/** Every language's string for one key - the Settings search matches in both. */
function tAll(key) {
  return Object.values(I18N_DICT)
    .map((dict) => dict[key])
    .filter((str) => typeof str === 'string');
}

/** Sets the current language (unknown => 'pl'). */
function setLang(lang) {
  currentLang = I18N_DICT[lang] ? lang : 'pl';
}

/** Fills in static labels in the DOM (textContent / placeholder / title). */
function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPh));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  });
  // An icon-only control (the Ctrl+B directory's × button) has no text node to
  // translate - its accessible name IS the aria-label, so without this pass a
  // screen reader would read the authored Polish to an English user.
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.documentElement.lang = currentLang;
}

window.i18n = {
  t,
  tAll,
  setLang,
  applyStatic,
  get lang() {
    return currentLang;
  },
};

