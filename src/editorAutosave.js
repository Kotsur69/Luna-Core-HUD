// ============================================================================
// LunaCore - editor auto-save for Unity and Blender
// ----------------------------------------------------------------------------
// A PC that crashes at random must not cost unsaved editor work. LunaCore
// cannot press Ctrl+S inside another app reliably (a synthetic key needs the
// window focused and lands in whatever is being typed or dragged), so the
// save runs INSIDE each editor, from a small script LunaCore installs:
//
//   Unity    <project>/Assets/Editor/LunaCoreAutoSave.cs
//            every N minutes: saves the dirty, already-named open scenes and
//            the modified assets. Never in play mode, while compiling,
//            importing or building. The file lives in the project, so it
//            reaches the other PC through git.
//   Blender  <config>/<version>/scripts/startup/lunacore_autosave.py
//            every N minutes: saves the .blend when it has a path and unsaved
//            changes. A file that was never saved is left to Blender's own
//            temp auto-save.
//
// Both keep working while LunaCore is closed. Install / remove are explicit
// (Settings -> General -> Editor auto-save); nothing is written on its own.
// Every generated file starts with MARKER: only a file carrying it is ever
// overwritten or removed, so a script of the same name that Mati wrote
// himself is left alone.
// ============================================================================

'use strict';

const fs = require('fs');
const path = require('path');

const MARKER = 'LunaCore auto-save (generated by LunaCore';
const INTERVAL_MINUTES = Object.freeze([2, 5, 10, 15]);
const DEFAULT_MINUTES = 5;
const UNITY_SCRIPT = path.join('Assets', 'Editor', 'LunaCoreAutoSave.cs');
const BLENDER_SCRIPT = path.join('scripts', 'startup', 'lunacore_autosave.py');
const BLENDER_VERSION_RE = /^\d+\.\d+$/;
const MAX_PROJECTS = 50;

/** A minutes value the UI may send; anything else is the default. */
function cleanMinutes(value) {
  return INTERVAL_MINUTES.includes(value) ? value : DEFAULT_MINUTES;
}

/** The interval a generated script was written with, or null when unreadable. */
function scriptMinutes(text) {
  const m = /interval: (\d+) min/.exec(String(text || ''));
  const n = m ? Number(m[1]) : NaN;
  return INTERVAL_MINUTES.includes(n) ? n : null;
}

/** The Unity editor script. Pure. */
function unityScript(minutes) {
  const min = cleanMinutes(minutes);
  return [
    `// ${MARKER} - interval: ${min} min).`,
    '// Reinstall from LunaCore Settings -> General -> Editor auto-save to change',
    '// the interval; remove it there too. Editor only - never part of a build.',
    '#if UNITY_EDITOR',
    'using UnityEditor;',
    'using UnityEditor.SceneManagement;',
    'using UnityEngine;',
    'using UnityEngine.SceneManagement;',
    '',
    '[InitializeOnLoad]',
    'internal static class LunaCoreAutoSave',
    '{',
    `    private const double IntervalSeconds = ${min * 60};`,
    '    private static double nextSaveAt;',
    '',
    '    static LunaCoreAutoSave()',
    '    {',
    '        nextSaveAt = EditorApplication.timeSinceStartup + IntervalSeconds;',
    '        EditorApplication.update += Tick;',
    '    }',
    '',
    '    private static void Tick()',
    '    {',
    '        if (EditorApplication.timeSinceStartup < nextSaveAt) return;',
    '        nextSaveAt = EditorApplication.timeSinceStartup + IntervalSeconds;',
    '        // Saving is refused or unsafe in these states; the next tick tries again.',
    '        if (EditorApplication.isPlayingOrWillChangePlaymode || EditorApplication.isCompiling',
    '            || EditorApplication.isUpdating || BuildPipeline.isBuildingPlayer) return;',
    '',
    '        int saved = 0;',
    '        for (int i = 0; i < SceneManager.sceneCount; i++)',
    '        {',
    '            Scene scene = SceneManager.GetSceneAt(i);',
    '            // An untitled scene would open a "Save as" dialog: left to the user.',
    '            if (!scene.isLoaded || !scene.isDirty || string.IsNullOrEmpty(scene.path)) continue;',
    '            if (EditorSceneManager.SaveScene(scene)) saved++;',
    '        }',
    '        AssetDatabase.SaveAssets();',
    '        if (saved > 0) Debug.Log("[LunaCore] Auto-saved " + saved + " scene(s).");',
    '    }',
    '}',
    '#endif',
    '',
  ].join('\n');
}

/** The Blender startup script. Pure. */
function blenderScript(minutes) {
  const min = cleanMinutes(minutes);
  return [
    `# ${MARKER} - interval: ${min} min).`,
    '# Reinstall from LunaCore Settings -> General -> Editor auto-save to change',
    '# the interval; remove it there too.',
    'import bpy',
    '',
    `INTERVAL_SECONDS = ${min * 60}.0`,
    '',
    '',
    'def _lunacore_autosave():',
    '    try:',
    '        # A file that was never saved has no path: Blender\'s own temp',
    '        # auto-save covers it. Nothing to do when nothing changed.',
    '        if not bpy.app.background and bpy.data.filepath and bpy.data.is_dirty:',
    '            bpy.ops.wm.save_mainfile()',
    '    except Exception as err:  # a failed save must never stop the timer',
    '        print("[LunaCore] auto-save failed:", err)',
    '    return INTERVAL_SECONDS',
    '',
    '',
    'def register():',
    '    if not bpy.app.timers.is_registered(_lunacore_autosave):',
    '        bpy.app.timers.register(_lunacore_autosave, first_interval=INTERVAL_SECONDS, persistent=True)',
    '',
    '',
    'def unregister():',
    '    if bpy.app.timers.is_registered(_lunacore_autosave):',
    '        bpy.app.timers.unregister(_lunacore_autosave)',
    '',
  ].join('\n');
}

/**
 * @param {object} deps
 * @param {() => Array<{name?: string, path?: string}>} deps.projects registered LunaCore projects
 * @param {() => string|null} deps.blenderConfigDir e.g. %APPDATA%/Blender Foundation/Blender
 * @param {object} [deps.fsImpl]
 * @param {(line: string) => void} [deps.log]
 */
function createEditorAutosave({ projects, blenderConfigDir, fsImpl = fs, log = () => {} }) {
  const isDir = (p) => {
    try {
      return fsImpl.statSync(p).isDirectory();
    } catch {
      return false;
    }
  };
  const isFile = (p) => {
    try {
      return fsImpl.statSync(p).isFile();
    } catch {
      return false;
    }
  };
  const readOrNull = (p) => {
    try {
      return fsImpl.readFileSync(p, 'utf8');
    } catch {
      return null;
    }
  };
  const isUnityProject = (dir) => isDir(path.join(dir, 'Assets')) && isFile(path.join(dir, 'ProjectSettings', 'ProjectVersion.txt'));

  /** Unity projects among the registered projects: the folder itself or a direct child. */
  function unityTargets() {
    const out = [];
    const seen = new Set();
    const add = (dir, name) => {
      const key = path.resolve(dir).toLowerCase();
      if (seen.has(key) || out.length >= MAX_PROJECTS || !isUnityProject(dir)) return;
      seen.add(key);
      out.push({ kind: 'unity', name, dir, file: path.join(dir, UNITY_SCRIPT) });
    };
    const list = projects();
    for (const project of Array.isArray(list) ? list : []) {
      const root = project && typeof project.path === 'string' ? project.path : '';
      if (!root || !isDir(root)) continue;
      const name = typeof project.name === 'string' && project.name ? project.name : path.basename(root);
      add(root, name);
      let children = [];
      try {
        children = fsImpl.readdirSync(root);
      } catch {
        children = [];
      }
      for (const child of children) {
        if (child.startsWith('.') || child === 'node_modules') continue;
        add(path.join(root, child), `${name}/${child}`);
      }
    }
    return out;
  }

  /** One target per installed Blender version (its user config folder). */
  function blenderTargets() {
    const base = blenderConfigDir();
    if (!base || !isDir(base)) return [];
    let versions = [];
    try {
      versions = fsImpl.readdirSync(base);
    } catch {
      versions = [];
    }
    return versions
      .filter((v) => BLENDER_VERSION_RE.test(v) && isDir(path.join(base, v)))
      .sort((a, b) => Number(a) - Number(b))
      .map((v) => ({ kind: 'blender', name: `Blender ${v}`, dir: path.join(base, v), file: path.join(base, v, BLENDER_SCRIPT) }));
  }

  const targets = () => [...unityTargets(), ...blenderTargets()];

  /** True when the path exists and is a symlink / junction (never written through). */
  const isLink = (p) => {
    try {
      return fsImpl.lstatSync(p).isSymbolicLink();
    } catch {
      return false;
    }
  };

  /** installed / foreign (a same-named file that is not ours) / absent, per target. */
  function stateOf(target) {
    // A link could point the write outside the project: treated as not ours.
    const folder = path.dirname(target.file);
    if ([target.dir, path.dirname(folder), folder, target.file].some(isLink)) return { state: 'foreign', minutes: null };
    const text = readOrNull(target.file);
    if (text === null) return { state: 'absent', minutes: null };
    return text.includes(MARKER) ? { state: 'installed', minutes: scriptMinutes(text) } : { state: 'foreign', minutes: null };
  }

  const row = (target, extra = {}) => ({ kind: target.kind, name: target.name, ...stateOf(target), ...extra });

  return {
    /** What could be covered and what already is. No paths leave main. */
    status() {
      return { minutes: [...INTERVAL_MINUTES], targets: targets().map((t) => row(t)) };
    },

    /** Writes / refreshes the script in every target; a foreign file is never touched. */
    install(minutes) {
      const min = cleanMinutes(minutes);
      return {
        targets: targets().map((target) => {
          if (stateOf(target).state === 'foreign') return row(target, { ok: false, error: 'foreign' });
          try {
            fsImpl.mkdirSync(path.dirname(target.file), { recursive: true });
            fsImpl.writeFileSync(target.file, target.kind === 'unity' ? unityScript(min) : blenderScript(min), 'utf8');
            return row(target, { ok: true });
          } catch (err) {
            log(`[autosave] could not install into ${target.name}: ${err && err.message}`);
            return row(target, { ok: false, error: 'writeFailed' });
          }
        }),
      };
    },

    /** Removes only files LunaCore generated (Unity's .meta next to it too). */
    remove() {
      return {
        targets: targets().map((target) => {
          if (stateOf(target).state !== 'installed') return row(target, { ok: true });
          try {
            fsImpl.unlinkSync(target.file);
            if (target.kind === 'unity' && isFile(`${target.file}.meta`)) fsImpl.unlinkSync(`${target.file}.meta`);
            return row(target, { ok: true });
          } catch (err) {
            log(`[autosave] could not remove from ${target.name}: ${err && err.message}`);
            return row(target, { ok: false, error: 'removeFailed' });
          }
        }),
      };
    },
  };
}

module.exports = {
  createEditorAutosave,
  unityScript,
  blenderScript,
  cleanMinutes,
  scriptMinutes,
  MARKER,
  INTERVAL_MINUTES,
  DEFAULT_MINUTES,
  UNITY_SCRIPT,
  BLENDER_SCRIPT,
};
